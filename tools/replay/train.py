# Trains the kill-prediction model from a dataset made with: go run . -dataset dataset.csv <demos>
# Usage: python train.py dataset.csv models_out   (needs pandas + scikit-learn)
# Writes <demo>.json held-out models (for go run . -modeldir models_out ...), full.json and model.go
# (copy model.go to gui/director/model.go to update the app's built-in model).
# Train logistic regression; write leave-one-demo-out models + full model (JSON and Go)
import pandas as pd, json, os, sys
from sklearn.linear_model import LogisticRegression
df = pd.read_csv(sys.argv[1] if len(sys.argv)>1 else '/tmp/ds.csv')
out = sys.argv[2] if len(sys.argv)>2 else '/home/claude/ml/models'
os.makedirs(out, exist_ok=True)
feats = [c for c in df.columns if c not in ('demo','round','t','id','kill1','kill2','kill3','inv1','inv2','inv3')]
def fit(d):
    m = LogisticRegression(max_iter=3000).fit(d[feats], d['kill3'])
    return {"features": feats, "coef": [round(float(c),5) for c in m.coef_[0]], "intercept": round(float(m.intercept_[0]),5)}
for dname in sorted(df.demo.unique()):
    json.dump(fit(df[df.demo!=dname]), open(f"{out}/{dname}.json","w"), indent=1)
full = fit(df)
json.dump(full, open(f"{out}/full.json","w"), indent=1)
go = ["package director", "", "// Code generated by tools/replay/train.py from real demos. DO NOT EDIT.", "",
      "// DefaultModel is the built-in kill-prediction model.", "func DefaultModel() *Model {", "\treturn &Model{",
      "\t\tFeatures: []string{" + ", ".join(f'"{f}"' for f in feats) + "},",
      "\t\tCoef: []float64{" + ", ".join(str(c) for c in full["coef"]) + "},",
      f"\t\tIntercept: {full['intercept']},", "\t}", "}", ""]
open(f"{out}/model.go","w").write("\n".join(go))
print("ok", len(feats), "features")
